// Regenerates services/databaseApi/index.js from the folders. Run after adding a data function:
//   node src/scripts/buildDatabaseApiIndex.js
import { readdirSync, writeFileSync, statSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const dir = fileURLToPath(new URL('../services/databaseApi/', import.meta.url));
const lines = ['// Generated by src/scripts/buildDatabaseApiIndex.js. One data function per file.', ''];
for (const entity of readdirSync(dir).sort()) {
  if (!statSync(join(dir, entity)).isDirectory()) continue;
  lines.push(`// ${entity}`);
  for (const file of readdirSync(join(dir, entity)).sort()) {
    if (!file.endsWith('.js') || file.endsWith('.spec.js')) continue;
    lines.push(`export { default as ${file.replace('.js', '')} } from './${entity}/${file}';`);
  }
  lines.push('');
}
writeFileSync(join(dir, 'index.js'), lines.join('\n'));
console.log('databaseApi/index.js updated');
